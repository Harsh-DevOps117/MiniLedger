async function caption(title, detail) {
  console.info(title);
  await page.evaluate(
    ({ title, detail }) => {
      let panel = document.getElementById('demo-caption');
      if (!panel) {
        panel = document.createElement('div');
        panel.id = 'demo-caption';
        panel.style.cssText =
          'position:fixed;bottom:0;left:0;right:0;z-index:2147483647;background:#142e2c;color:white;padding:16px 32px;font:16px/1.5 system-ui;pointer-events:none;border-top:3px solid #91b5a3';
        document.body.appendChild(panel);
      }
      panel.replaceChildren();
      const strong = document.createElement('strong');
      strong.textContent = title;
      const body = document.createElement('div');
      body.textContent = detail;
      body.style.cssText = 'font-size:13px;color:#c5dcd0';
      panel.append(strong, body);
    },
    { title, detail },
  );
}
async function pause(seconds) {
  await page.waitForTimeout(seconds * 1000);
}
async function fillEntry(friend, amount, dueDate) {
  await page.getByRole('button', { name: '+ Add entry', exact: true }).click();
  await page
    .getByRole('textbox', { name: 'Friend’s name' })
    .pressSequentially(friend, { delay: 65 });
  await page
    .getByRole('textbox', { name: 'Amount (INR)', exact: true })
    .pressSequentially(amount, { delay: 130 });
  await page.getByRole('button', { name: 'Choose due date', exact: true }).click();
  const current = new Date();
  const target = new Date(`${dueDate}T00:00:00Z`);
  const months =
    (target.getUTCFullYear() - current.getUTCFullYear()) * 12 +
    target.getUTCMonth() -
    current.getUTCMonth();
  for (let index = 0; index < Math.abs(months); index++) {
    await page
      .getByRole('button', { name: months > 0 ? 'Next month' : 'Previous month', exact: true })
      .click();
  }
  await page.getByRole('button', { name: `Select ${dueDate}`, exact: true }).click();
}
